export function icon(name, { size = 18, cls = "" } = {}) {
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.8");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.setAttribute("class", `icon${cls ? ` ${cls}` : ""}`);
  svg.innerHTML = PATHS[name] || "";
  return svg;
}

// Replace <i data-icon="name" data-size="18"> placeholders in static markup.
export function hydrateIcons(root = document) {
  for (const placeholder of root.querySelectorAll("i[data-icon]")) {
    const svg = icon(placeholder.dataset.icon, {
      size: Number(placeholder.dataset.size) || 18,
      cls: placeholder.className,
    });
    placeholder.replaceWith(svg);
  }
}

export function setIcon(button, name, size) {
  const current = button.querySelector("svg.icon");
  const next = icon(name, { size: size || Number(current?.getAttribute("width")) || 18 });
  if (current) current.replaceWith(next);
  else button.prepend(next);
}
